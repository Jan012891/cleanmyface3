(function(){
'use strict';
const prods=window.CMF.products;
const featured=[prods[4],prods[0],prods[2],prods[3]];
const bestseller=document.getElementById('bestseller-grid');
bestseller.innerHTML=featured.map(p=>window.CMF.renderCard(p)).join('');
const track=document.getElementById('carousel-track');
const container=document.getElementById('product-carousel');
const desktopMedia=window.matchMedia('(min-width: 701px)');
const desktopList=[prods[1],prods[0],prods[2],prods[3],prods[5],prods[4],prods[6],prods[7]];
const mobileList=prods.slice();
let list=[],n=0,index=0,animating=false,hovering=false,dragStart=null,showcase=false;
const escape=window.CMF.escapeHtml;
const showcaseItem=p=>`<a class="showcase-item" data-product-id="${p.id}" href="product.html?id=${p.id}" aria-label="View ${escape(p.name)}"><div class="showcase-thumb"><img loading="lazy" src="assets/${p.image}" alt="${escape(p.name)}"></div><div class="showcase-meta"><h3>${escape(p.name)}</h3><p>${escape(p.description.replace(/\.$/,''))}</p></div></a>`;
const cardItem=(p,i)=>`<div class="carousel-item" data-carousel-index="${i%n}">${window.CMF.renderCard(p)}</div>`;
const metrics=()=>{const one=track.children[0]; if(!one)return {width:0,gap:0,step:0}; const style=getComputedStyle(track); const gap=parseFloat(style.columnGap||style.gap)||0; const width=one.getBoundingClientRect().width; return {width,gap,step:width+gap}};
const setActive=()=>{Array.from(track.children).forEach((el,i)=>el.classList.toggle('is-active',showcase && i===index));};
const position=(animate=false)=>{const {width,step}=metrics(); if(!step)return; const centerOffset=showcase ? Math.max(0,(container.clientWidth-width)/2) : 0; track.style.transition=animate?'transform 620ms cubic-bezier(.24,.72,.23,1)':'none'; track.style.transform=`translate3d(${centerOffset-index*step}px,0,0)`; setActive();};
const build=()=>{
  showcase=desktopMedia.matches;
  list=(showcase?desktopList:mobileList).filter(Boolean);
  n=list.length;
  if(!n) return;
  track.classList.toggle('is-showcase',showcase);
  track.innerHTML=[...list,...list,...list].map((p,i)=>showcase?showcaseItem(p):cardItem(p,i)).join('');
  index=n+(showcase?3:0);
  animating=false;
  requestAnimationFrame(()=>position(false));
};
const go=delta=>{if(animating||!n)return; animating=true; index+=delta; position(true);};
track.addEventListener('transitionend',e=>{if(e.propertyName!=='transform')return; animating=false; if(index>=2*n){index-=n; position(false)} else if(index<n){index+=n; position(false)} else {setActive();}});
document.getElementById('carousel-prev').addEventListener('click',()=>go(-1));
document.getElementById('carousel-next').addEventListener('click',()=>go(1));
container.addEventListener('pointerdown',e=>{if(e.pointerType==='mouse'&&e.button!==0)return; dragStart={x:e.clientX,t:Date.now()};});
container.addEventListener('pointerup',e=>{if(!dragStart)return; const delta=e.clientX-dragStart.x; if(Math.abs(delta)>38)go(delta<0?1:-1); dragStart=null;});
container.addEventListener('pointercancel',()=>dragStart=null);
container.addEventListener('mouseenter',()=>hovering=true);
container.addEventListener('mouseleave',()=>hovering=false);
container.addEventListener('focusin',()=>hovering=true);
container.addEventListener('focusout',()=>hovering=false);
let resizeTimer;
window.addEventListener('resize',()=>{clearTimeout(resizeTimer); resizeTimer=setTimeout(()=>{const shouldShowcase=desktopMedia.matches; if(shouldShowcase!==showcase){build();} else {position(false);} },120);});
requestAnimationFrame(build);
setInterval(()=>{if(!document.hidden&&!hovering&&!animating&&!window.matchMedia('(prefers-reduced-motion: reduce)').matches)go(1)},3400);
})();
